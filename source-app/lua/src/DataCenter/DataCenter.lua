local DataCenter = {}

local function GetPathByType(type)
  local path
  if type == "WorldMarchDataManager" then
    if CS.ClientConfig.NEW_MARCH_DATA_MANAGER then
      path = "DataCenter.WorldMarchDataManager.WorldMarchDataProxy"
      Logger.Log("LuaWorldMarchDataProxy")
    else
      path = "DataCenter.WorldMarchDataManager.WorldMarchDataManager"
      Logger.Log("LuaWorldMarchDataManager")
    end
  else
    path = Managers[type]
  end
  return path
end

return setmetatable(DataCenter, {
  __index = function(t, k)
    local manager = Managers[k]
    if manager ~= nil then
      local loaded = require(manager)
      if type(loaded) ~= "table" then
        CS.GameEntry.DebugLuaFile(manager)
      end
      local inst = loaded.New()
      t[k] = inst
      return inst
    end
    return nil
  end
})
